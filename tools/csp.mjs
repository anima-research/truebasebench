#!/usr/bin/env node
// Writes the Content-Security-Policy header for the built site as a Caddyfile snippet.
//
//   node tools/csp.mjs site/dist/index.html /etc/caddy/csp.caddy
//
// - script-src: 'self' plus the sha256 of every inline <script> in the built index.html (the theme bootstrap),
//   so no 'unsafe-inline' is needed for scripts.
// - connect-src: 'self' plus the origin of VITE_DATA_BASE_URL (the OVH bucket), read from the environment.
// - style-src keeps 'unsafe-inline' because React renders style="" attributes.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const [, , htmlPath = "site/dist/index.html", outPath = "-"] = process.argv;
const html = readFileSync(htmlPath, "utf8");

const hashes = [];
for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
  if (/\bsrc\s*=/.test(m[1])) continue;
  hashes.push(`'sha256-${createHash("sha256").update(m[2], "utf8").digest("base64")}'`);
}

const connect = ["'self'"];
const dataBase = (process.env.VITE_DATA_BASE_URL || "").trim();
if (dataBase) {
  let origin;
  try {
    origin = new URL(dataBase).origin;
  } catch {
    console.error(`csp: VITE_DATA_BASE_URL is not an absolute URL: ${dataBase}`);
    process.exit(1);
  }
  if (!origin.startsWith("https://") && !origin.startsWith("http://localhost")) {
    console.error(`csp: VITE_DATA_BASE_URL must be https: ${dataBase}`);
    process.exit(1);
  }
  connect.push(origin);
}

const policy = [
  "default-src 'self'",
  `script-src 'self' ${hashes.join(" ")}`.trim(),
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self' data:",
  `connect-src ${connect.join(" ")}`,
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "manifest-src 'self'",
  "worker-src 'self'",
].join("; ");

const snippet = `# generated by tools/csp.mjs at build time; do not edit\nheader Content-Security-Policy "${policy}"\n`;
if (outPath === "-") process.stdout.write(snippet);
else writeFileSync(outPath, snippet);
console.error(`csp: ${hashes.length} inline script hash(es); connect-src ${connect.join(" ")}`);
